import re
from abc import ABC, abstractmethod
from collections.abc import Mapping, Sequence
from typing import Any

from .schemas import CANONICAL_ROLES, Reply, UnknownRoleError

RE_REASONING_TAGS = re.compile(r'<(reasoning|think)>.*?</\1>', flags=re.DOTALL)


class BaseLLMModel(ABC):
    """Define the shared implementation for asynchronous model providers."""

    def __init__(self, allowed_roles: set[str] | None = None) -> None:
        """
        Initialize the model with a set of allowed message roles.

        Args:
            allowed_roles (set[str] | None): Set of roles supported by the model.
            If not provided, canonical roles are used.
        """
        self.allowed_roles = set(CANONICAL_ROLES) if allowed_roles is None else set(allowed_roles)

    def _validate_roles(self, messages: Sequence[Mapping[str, Any]]) -> None:
        """
        Validate message roles against the allowed role set.

        Args:
            messages (Sequence[Mapping[str, Any]]): Messages to validate.

        Raises:
            UnknownRoleError: If a message contains an unsupported role.
        """
        for message in messages:
            if message.get('role') not in self.allowed_roles:
                raise UnknownRoleError(
                    f"{self.__class__.__name__}: Unknown role '{message.get('role')}'. "
                    f"Allowed roles: {sorted(self.allowed_roles)}"
                )

    @property
    @abstractmethod
    def model_name(self) -> str:
        ...

    @abstractmethod
    async def chat(
            self,
            messages: Sequence[Mapping[str, Any]],
            tools: Sequence[dict[str, Any]] | None = None,
            timeout: float | None = None,
    ) -> Reply:
        """
        Generate a response for the Agent.

        Args:
            messages (Sequence[Mapping[str, Any]]): Dialogue context.
            tools: (Sequence[dict[str, Any]], optional): Available tool schemas.
            timeout (float | None, optional): Maximum time to wait for the request.

        Returns:
            Reply: Model response including text, tool calls, token usage and cost.
        """
        pass

    @staticmethod
    def _postprocess(text: str) -> str:
        """
        Clean the model output.

        Args:
            text (str): The raw text generated by the model.

        Returns:
            str: The cleaned text containing only the core response.
        """
        cleaned_text = RE_REASONING_TAGS.sub('', text)
        processed_text = cleaned_text.strip()

        return processed_text
